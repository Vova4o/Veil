PROFILE = APPROVED_PROFILES["krea2_moody_v40"]

# The shape ComfyUI Desktop writes into instance-model-paths/inst-*.yaml.
DESKTOP_YAML = """# Generated by Comfy Desktop — do not edit manually.

comfy.desktop_0:
  base_path: '{base}'
  is_default: true
  'checkpoints': 'checkpoints/'
  'controlnet': |-
    controlnet/
    t2i_adapter/
  'diffusion_models': 'diffusion_models/'
  'loras': 'loras/'
  'text_encoders': 'text_encoders/'
  'vae': 'vae/'
  'clip': 'clip/'
  'unet': 'unet/'
"""


def _comfy(tmp_path):
    comfy_dir = tmp_path / "ComfyUI"
    comfy_dir.mkdir()
    (comfy_dir / "main.py").write_text("", encoding="utf-8")
    return comfy_dir


def _desktop(tmp_path):
    """A Desktop-like install: models live in a shared folder named by an extra paths config."""
    comfy_dir = _comfy(tmp_path)
    shared = tmp_path / "Shared" / "models"
    config = tmp_path / "Desktop Config" / "inst.yaml"
    config.parent.mkdir()
    config.write_text(DESKTOP_YAML.format(base=shared), encoding="utf-8")
    extra_args = f"--extra-model-paths-config '{config.as_posix()}' --input-directory {tmp_path.as_posix()}/in"
    return comfy_dir, shared, extra_args


def _store(tmp_path, **settings):
    store = ConfigStore(tmp_path / "config.json")
    store.update_comfyui_settings(**settings)
    return store


def test_parse_model_paths_yaml_reads_quotes_booleans_blocks_and_comments():
    sections = parse_model_paths_yaml(
        "﻿# comment\n"
        "a111:\n"
        "    base_path: path/to/webui/  # trailing comment\n"
        "    is_default: True\n"
        "    checkpoints: models/Stable-diffusion\n"
        "    loras: |\n"
        "         models/Lora\n"
        "         models/LyCORIS\n"
        "    \"vae\": \"models/V#AE\"\n"
        "other:\n"
        "  'text_encoders': 'it''s/here'\n"
        "empty:\n"
    )
    assert sections["a111"] == {
        "base_path": "path/to/webui/",
        "is_default": True,
        "checkpoints": "models/Stable-diffusion",
        "loras": "models/Lora\nmodels/LyCORIS",
        "vae": "models/V#AE",
    }
    assert sections["other"] == {"text_encoders": "it's/here"}
    assert sections["empty"] == {}


def test_desktop_config_puts_shared_folders_first_like_comfyui(tmp_path):
    comfy_dir, shared, extra_args = _desktop(tmp_path)
    folders = model_folders(comfy_dir, extra_args)

    assert folders.models_dir == comfy_dir / "models"
    # Later default entries move to the front, so the legacy "unet" folder leads, as in ComfyUI.
    assert folders.search_paths("diffusion_models") == [
        shared / "unet",
        shared / "diffusion_models",
        comfy_dir / "models" / "unet",
        comfy_dir / "models" / "diffusion_models",
    ]
    assert folders.search_paths("unet") == folders.search_paths("diffusion_models")
    assert folders.search_paths("controlnet")[:2] == [shared / "t2i_adapter", shared / "controlnet"]
    assert folders.search_paths("upscale_models") == [comfy_dir / "models" / "upscale_models"]
    # New files go to the folder the config names for exactly this folder.
    assert folders.download_dir("diffusion_models") == shared / "diffusion_models"
    assert folders.download_dir("text_encoders") == shared / "text_encoders"
    assert folders.download_dir("upscale_models") == comfy_dir / "models" / "upscale_models"


def test_model_folders_follow_base_directory_and_local_config(tmp_path):
    comfy_dir = _comfy(tmp_path)
    (comfy_dir / "extra_model_paths.yaml").write_text("local:\n  loras: ../more_loras\n", encoding="utf-8")
    folders = model_folders(comfy_dir, f"--base-directory={(tmp_path / 'base').as_posix()} --lowvram")

    assert folders.models_dir == tmp_path / "base" / "models"
    # Without base_path a relative entry is relative to the config's folder; non-default entries go last.
    assert folders.search_paths("loras") == [tmp_path / "base" / "models" / "loras", tmp_path / "more_loras"]
    assert folders.download_dir("loras") == tmp_path / "base" / "models" / "loras"


def test_model_folders_ignore_unsafe_or_missing_settings(tmp_path):
    comfy_dir = _comfy(tmp_path)
    assert model_folders(comfy_dir, "--extra-model-paths-config x.yaml & calc").models_dir == comfy_dir / "models"
    assert resolve_model_folders({}) is None
    assert resolve_model_folders({"install_path": str(tmp_path / "nowhere")}) is None


class _OfflineClient:
    def get_object_info(self):
        raise ComfyUIClientError("connection refused")


def test_offline_inventory_sees_models_in_desktop_shared_folder(tmp_path):
    comfy_dir, shared, extra_args = _desktop(tmp_path)
    for dep in PROFILE.required_resources:
        target = shared / dep.folder / dep.filename
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(b"x")
    (shared / "unet" / "old" / "legacy.safetensors").parent.mkdir(parents=True)
    (shared / "unet" / "old" / "legacy.safetensors").write_bytes(b"x")
    store = _store(tmp_path, install_path=str(comfy_dir), extra_args=extra_args)

    inventory = collect_runtime_inventory(store, client=_OfflineClient())

    assert inventory.online is False
    assert inventory.source == "filesystem"
    # Like the API, old folder names are listed under their current names only.
    assert "unet" not in inventory.models
    assert "old/legacy.safetensors" in inventory.models["diffusion_models"]

    health = check_profile_health(PROFILE, inventory, installed_node_packs={"comfyui-krea2edit"})
    assert health["status"] == "ready"
    assert health["comfyui_online"] is False
    assert health["missing_resources"] == []
    assert health["modes_ready"] == {"text": True, "reference": True, "variation": True, "edit": True}


def test_offline_health_without_comfyui_folder_is_unknown_not_missing():
    inventory = SimpleNamespace(online=False, node_types=[], models={}, source="none")
    health = check_profile_health(PROFILE, inventory)
    assert health["status"] == "unknown"
    assert health["missing_resources"] == []
    assert health["comfyui_online"] is False


def test_downloads_go_to_the_default_shared_folder(tmp_path, monkeypatch):
    monkeypatch.setattr(simple_downloader, "_ensure_schema", lambda: None)
    comfy_dir, shared, extra_args = _desktop(tmp_path)
    service = SimpleModelDownloaderService(_store(tmp_path, install_path=str(comfy_dir), extra_args=extra_args))

    target, part = service._resolve_target("loras", "../escape/style.safetensors")

    assert target == (shared / "loras" / "style.safetensors").resolve()
    assert part == target.with_name("style.safetensors.part")
    assert service.resolve_model_root() == (comfy_dir / "models").resolve()


def test_downloads_without_extra_paths_keep_the_install_models_folder(tmp_path, monkeypatch):
    monkeypatch.setattr(simple_downloader, "_ensure_schema", lambda: None)
    comfy_dir = _comfy(tmp_path)
    service = SimpleModelDownloaderService(_store(tmp_path, install_path=str(comfy_dir)))

    target, _ = service._resolve_target("diffusion_models", "model.safetensors")

    assert target == (comfy_dir / "models" / "diffusion_models" / "model.safetensors").resolve()
